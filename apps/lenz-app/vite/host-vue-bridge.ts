import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import * as Vue from "vue";
import type { Plugin } from "vite-plus";

/**
 * Writes public/host/vue.js: an ES module that re-exports the Vue instance the
 * app puts on `window.__lenz_vue`. The export list comes from the installed Vue,
 * so it never goes stale. Extensions build with `vue` external; the import map
 * in index.html resolves it to this file.
 */
export function hostVueBridge(): Plugin {
  return {
    name: "lenz:host-vue-bridge",
    buildStart() {
      const names = Object.keys(Vue).filter((name) => /^[A-Za-z_$][\w$]*$/.test(name));
      const source = [
        "// Generated by vite/host-vue-bridge.ts. Do not edit.",
        "const Vue = window.__lenz_vue",
        'if (!Vue) throw new Error("The host must expose window.__lenz_vue before extensions load.")',
        "export default Vue",
        `export const { ${names.join(", ")} } = Vue`,
        "",
      ].join("\n");
      const file = resolve(import.meta.dirname, "../public/host/vue.js");
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, source);
    },
  };
}
