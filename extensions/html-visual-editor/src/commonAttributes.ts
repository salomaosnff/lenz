/** Useful on almost any element. */
const general = ["title", "lang", "hidden", "tabindex"];

/** Common attributes of `tag`, most specific first. */
export function commonAttributesOf(tag: string): string[] {
  return [...(Object.hasOwn(byTag, tag) ? byTag[tag]! : []), ...general];
}
